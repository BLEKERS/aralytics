-- Aralytics ERD schema, PostgreSQL 16 baseline.
-- Replaces the legacy MySQL V1 + V3 + V4 + V5 + V6 + V7 migrations
-- (preserved under db/migration_mysql_legacy). Identifiers are unquoted so
-- PostgreSQL folds them to lowercase; JPA uses PhysicalNamingStrategyStandardImpl.
-- All timestamps are timestamptz (UTC), mapped to OffsetDateTime by Hibernate.

CREATE TABLE subscription (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan        VARCHAR(64) NOT NULL,
    startDate   DATE        NOT NULL,
    endDate     DATE        NOT NULL,
    status      VARCHAR(16) NOT NULL,
    maxStudents INT         NOT NULL,
    maxTeachers INT         NOT NULL,
    CONSTRAINT ck_subscription_status CHECK (status IN ('TRIAL', 'ACTIVE', 'EXPIRED', 'SUSPENDED'))
);

CREATE TABLE school (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                      VARCHAR(160) NOT NULL,
    address                   VARCHAR(255) NULL,
    contactEmail              VARCHAR(160) NULL,
    institutionCode           VARCHAR(64)  NOT NULL,
    studentActivationKeyHash  VARCHAR(64)  NULL,
    teacherActivationKeyHash  VARCHAR(64)  NULL,
    subscriptionId            BIGINT       NULL,
    CONSTRAINT uk_school_institution_code UNIQUE (institutionCode),
    CONSTRAINT fk_school_subscription FOREIGN KEY (subscriptionId) REFERENCES subscription (id)
);
CREATE INDEX idx_school_subscription ON school (subscriptionId);

-- app_user instead of USER: USER is a reserved SQL keyword in PostgreSQL.
CREATE TABLE app_user (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username     VARCHAR(64)  NOT NULL,
    passwordHash VARCHAR(100) NOT NULL,
    fullName     VARCHAR(160) NOT NULL,
    email        VARCHAR(160) NOT NULL,
    schoolId     BIGINT       NULL,
    role         VARCHAR(16)  NOT NULL,
    createdAt    TIMESTAMPTZ  NOT NULL,
    lastLogin    TIMESTAMPTZ  NULL,
    CONSTRAINT uk_user_username UNIQUE (username),
    CONSTRAINT uk_user_email UNIQUE (email),
    CONSTRAINT fk_user_school FOREIGN KEY (schoolId) REFERENCES school (id),
    CONSTRAINT chk_user_role CHECK (role IN ('STUDENT', 'TEACHER'))
);
CREATE INDEX idx_user_school ON app_user (schoolId);

CREATE TABLE class (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name      VARCHAR(160) NOT NULL,
    schoolId  BIGINT       NOT NULL,
    teacherId BIGINT       NULL,
    CONSTRAINT fk_class_school FOREIGN KEY (schoolId) REFERENCES school (id),
    CONSTRAINT fk_class_teacher FOREIGN KEY (teacherId) REFERENCES app_user (id)
);
CREATE INDEX idx_class_school ON class (schoolId);
CREATE INDEX idx_class_teacher ON class (teacherId);

CREATE TABLE enrollment (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    studentId BIGINT NOT NULL,
    classId   BIGINT NOT NULL,
    CONSTRAINT uk_enrollment_student_class UNIQUE (studentId, classId),
    CONSTRAINT fk_enrollment_student FOREIGN KEY (studentId) REFERENCES app_user (id),
    CONSTRAINT fk_enrollment_class FOREIGN KEY (classId) REFERENCES class (id)
);
CREATE INDEX idx_enrollment_class ON enrollment (classId);

CREATE TABLE quiz (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       VARCHAR(200) NOT NULL,
    description TEXT         NULL,
    classId     BIGINT       NOT NULL,
    createdBy   BIGINT       NOT NULL,
    dueDate     TIMESTAMPTZ  NULL,
    status      VARCHAR(16)  NOT NULL DEFAULT 'DRAFT',
    CONSTRAINT fk_quiz_class FOREIGN KEY (classId) REFERENCES class (id),
    CONSTRAINT fk_quiz_created_by FOREIGN KEY (createdBy) REFERENCES app_user (id),
    CONSTRAINT chk_quiz_status CHECK (status IN ('DRAFT', 'PUBLISHED', 'CLOSED'))
);
CREATE INDEX idx_quiz_class ON quiz (classId);
CREATE INDEX idx_quiz_created_by ON quiz (createdBy);

CREATE TABLE question (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quizId        BIGINT       NOT NULL,
    text          TEXT         NOT NULL,
    options       TEXT         NOT NULL,
    correctAnswer VARCHAR(16)  NOT NULL,
    points        INT          NOT NULL,
    CONSTRAINT fk_question_quiz FOREIGN KEY (quizId) REFERENCES quiz (id),
    CONSTRAINT chk_question_points CHECK (points >= 1)
);
CREATE INDEX idx_question_quiz ON question (quizId);

CREATE TABLE concept (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL,
    description VARCHAR(255) NULL,
    CONSTRAINT uk_concept_name UNIQUE (name)
);

-- ERD extension: per-question concept tags required by the diagnostic engine.
CREATE TABLE question_concept (
    questionId BIGINT NOT NULL,
    conceptId  BIGINT NOT NULL,
    PRIMARY KEY (questionId, conceptId),
    CONSTRAINT fk_question_concept_question FOREIGN KEY (questionId) REFERENCES question (id),
    CONSTRAINT fk_question_concept_concept FOREIGN KEY (conceptId) REFERENCES concept (id)
);
CREATE INDEX idx_question_concept_concept ON question_concept (conceptId);

CREATE TABLE submission (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    studentId   BIGINT        NOT NULL,
    quizId      BIGINT        NOT NULL,
    score       DECIMAL(5, 2) NOT NULL,
    submittedAt TIMESTAMPTZ   NOT NULL,
    CONSTRAINT uk_submission_student_quiz UNIQUE (studentId, quizId),
    CONSTRAINT fk_submission_student FOREIGN KEY (studentId) REFERENCES app_user (id),
    CONSTRAINT fk_submission_quiz FOREIGN KEY (quizId) REFERENCES quiz (id),
    CONSTRAINT chk_submission_score CHECK (score >= 0 AND score <= 100)
);
CREATE INDEX idx_submission_quiz ON submission (quizId);

CREATE TABLE answer (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submissionId   BIGINT       NOT NULL,
    questionId     BIGINT       NOT NULL,
    selectedOption VARCHAR(16)  NULL,
    isCorrect      BOOLEAN      NOT NULL,
    CONSTRAINT fk_answer_submission FOREIGN KEY (submissionId) REFERENCES submission (id),
    CONSTRAINT fk_answer_question FOREIGN KEY (questionId) REFERENCES question (id)
);
CREATE INDEX idx_answer_submission ON answer (submissionId);
CREATE INDEX idx_answer_question ON answer (questionId);

CREATE TABLE feedback (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submissionId BIGINT      NOT NULL,
    studentId    BIGINT      NOT NULL,
    content      TEXT        NOT NULL,
    generatedAt  TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_feedback_submission UNIQUE (submissionId),
    CONSTRAINT fk_feedback_submission FOREIGN KEY (submissionId) REFERENCES submission (id),
    CONSTRAINT fk_feedback_student FOREIGN KEY (studentId) REFERENCES app_user (id)
);
CREATE INDEX idx_feedback_student ON feedback (studentId);

CREATE TABLE feedback_concept (
    feedbackId BIGINT NOT NULL,
    conceptId  BIGINT NOT NULL,
    PRIMARY KEY (feedbackId, conceptId),
    CONSTRAINT fk_feedback_concept_feedback FOREIGN KEY (feedbackId) REFERENCES feedback (id),
    CONSTRAINT fk_feedback_concept_concept FOREIGN KEY (conceptId) REFERENCES concept (id)
);
CREATE INDEX idx_feedback_concept_concept ON feedback_concept (conceptId);

CREATE TABLE progress_record (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    studentId    BIGINT      NOT NULL,
    conceptId    BIGINT      NOT NULL,
    masteryLevel INT         NOT NULL,
    lastUpdated  TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_progress_student_concept UNIQUE (studentId, conceptId),
    CONSTRAINT fk_progress_student FOREIGN KEY (studentId) REFERENCES app_user (id),
    CONSTRAINT fk_progress_concept FOREIGN KEY (conceptId) REFERENCES concept (id),
    CONSTRAINT chk_progress_mastery CHECK (masteryLevel >= 0 AND masteryLevel <= 100)
);

CREATE TABLE notification (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    userId      BIGINT      NOT NULL,
    message     TEXT        NOT NULL,
    isRead      BOOLEAN     NOT NULL DEFAULT FALSE,
    scheduledAt TIMESTAMPTZ NULL,
    sentAt      TIMESTAMPTZ NULL,
    CONSTRAINT fk_notification_user FOREIGN KEY (userId) REFERENCES app_user (id)
);
CREATE INDEX idx_notification_user ON notification (userId);

CREATE TABLE teacher_settings (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    teacherId             BIGINT       NOT NULL,
    interventionThreshold INT          NOT NULL DEFAULT 70,
    feedbackTone          VARCHAR(32)  NOT NULL DEFAULT 'FORMAL',
    CONSTRAINT uk_teacher_settings_teacher UNIQUE (teacherId),
    CONSTRAINT fk_teacher_settings_teacher FOREIGN KEY (teacherId) REFERENCES app_user (id),
    CONSTRAINT chk_teacher_settings_threshold CHECK (interventionThreshold >= 0 AND interventionThreshold <= 100)
);

CREATE TABLE password_reset_tokens (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token       VARCHAR(64) NOT NULL,
    user_id     BIGINT      NOT NULL,
    expiry_date TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_password_reset_token UNIQUE (token),
    CONSTRAINT fk_password_reset_user FOREIGN KEY (user_id) REFERENCES app_user (id) ON DELETE CASCADE
);

CREATE TABLE quiz_draft (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id    BIGINT      NOT NULL,
    quiz_id       BIGINT      NOT NULL,
    answers_json  TEXT        NOT NULL,
    last_saved_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_quiz_draft_student_quiz UNIQUE (student_id, quiz_id),
    CONSTRAINT fk_quiz_draft_student FOREIGN KEY (student_id) REFERENCES app_user (id) ON DELETE CASCADE,
    CONSTRAINT fk_quiz_draft_quiz FOREIGN KEY (quiz_id) REFERENCES quiz (id) ON DELETE CASCADE
);
CREATE INDEX idx_quiz_draft_quiz ON quiz_draft (quiz_id);

CREATE TABLE pilot_inquiry (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_name  VARCHAR(160) NULL,
    contact_name VARCHAR(160) NULL,
    email        VARCHAR(160) NOT NULL,
    message      TEXT         NULL,
    created_at   TIMESTAMPTZ  NOT NULL
);
CREATE INDEX idx_pilot_inquiry_created ON pilot_inquiry (created_at);
